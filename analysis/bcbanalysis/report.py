"""Tables: CSV for further analysis, Markdown for reading, LaTeX (booktabs) for the paper."""
from __future__ import annotations

from collections import OrderedDict
from pathlib import Path

import pandas as pd

from . import fmt
from .crossover import find_crossover, outcomes
from .plots import _baseline, resolve_pairs
from .stats import METRIC_SHORT
from .workloads import WORKLOAD_ORDER, workload_info


def _wls(summary: pd.DataFrame) -> list[str]:
    present = set(summary["workload"])
    return [w for w in WORKLOAD_ORDER if w in present] + sorted(present - set(WORKLOAD_ORDER))


def _cell(g: pd.DataFrame, a: str, b: str, metric: str, pow2: bool, style: str) -> str:
    outs = outcomes(g, a, b, metric)
    rob, med = find_crossover(outs, "robust"), find_crossover(outs, "median")
    dash = "--" if style == "tex" else "—"

    def show(c):
        if c.status == "crossover":
            return fmt.size(c.size, pow2, style)
        return {"always": "all", "never": dash}.get(c.status, "n/a")

    s = show(rob)
    earlier = med.status in ("crossover", "always") and (
        rob.status not in ("crossover", "always") or (med.size or 0) < (rob.size or 0))
    if earlier:
        s += f" ({show(med)})"
    return s


def _pair_columns(summary: pd.DataFrame, baseline_override) -> list[tuple[str, str]]:
    """Union of resolved pairs, with the workload baseline written as BASE."""
    cols: OrderedDict[tuple[str, str], None] = OrderedDict()
    for wid in _wls(summary):
        g = summary[summary["workload"] == wid]
        base = _baseline(g, wid, baseline_override)
        for a, b in resolve_pairs(g, wid, baseline_override):
            cols[(a, "BASE" if b == base else b)] = None
    return list(cols)


def crossover_matrix(summary: pd.DataFrame, metrics: list[str], baseline_override, style: str):
    """Rows (workload, metric) × pair columns; cells are robust crossovers (median-only in parentheses)."""
    cols = _pair_columns(summary, baseline_override)
    rows = []
    for wid in _wls(summary):
        g = summary[summary["workload"] == wid]
        info = workload_info(wid)
        base = _baseline(g, wid, baseline_override)
        impls = set(g["implementation"])
        for metric in metrics:
            cells = []
            for a, b in cols:
                b = base if b == "BASE" else b
                cells.append(_cell(g, a, b, metric, info.pow2_labels, style) if a in impls and b in impls else "")
            rows.append((wid, info, base, metric, cells))
    return cols, rows


def markdown_table(summary: pd.DataFrame, metrics: list[str], baseline_override) -> str:
    cols, rows = crossover_matrix(summary, metrics, baseline_override, "text")
    head = ["Workload", "Metric"] + [f"{a} › {'JS' if b == 'BASE' else b}" for a, b in cols]
    lines = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    for wid, info, base, metric, cells in rows:
        name = f"{info.title} ({info.symbol})" + (f", JS = {base}" if base != "js" else "")
        lines.append("| " + " | ".join([name, METRIC_SHORT[metric], *cells]) + " |")
    return "\n".join(lines)


def latex_table(summary: pd.DataFrame, metrics: list[str], baseline_override, browser_label: str) -> str:
    cols, rows = crossover_matrix(summary, metrics, baseline_override, "tex")
    # Group columns by reference implementation for a two-level header.
    groups: OrderedDict[str, list[int]] = OrderedDict()
    for i, (_, b) in enumerate(cols):
        groups.setdefault(b, []).append(i)
    order = [i for idx in groups.values() for i in idx]
    tt = lambda s: r"\texttt{" + s + "}"
    th = lambda s: r"{\scriptsize\texttt{" + s + "}}"
    short = {"compute": "comp.", "e2e": "e2e", "kernel": "kernel"}
    out = [
        "% Generated by analysis/analyze.py. Requires \\usepackage{booktabs}.",
        r"\begin{table*}[t]",
        r"\centering\footnotesize",
        r"\setlength{\tabcolsep}{4pt}",
        r"\caption{Crossover sizes in " + browser_label.replace("_", r"\_") + r": the smallest size from which the "
        r"challenger's median time is lower than the reference's at every larger size of the sweep, with "
        r"non-overlapping interquartile ranges. In parentheses: the crossover by median alone, where it comes "
        r"earlier. ``all'': ahead at every size; ``--'': not ahead at the largest size. "
        r"comp.: compute phase; e2e: end-to-end (upload + compute + readback); kernel: GPU timestamps.}",
        r"\label{tab:crossovers}",
        r"\begin{tabular}{ll" + "r" * len(cols) + "}",
        r"\toprule",
    ]
    hdr1 = [r"\multicolumn{2}{l}{Challenger \textrightarrow}"]
    for b, idx in groups.items():
        ref = "JS" if b == "BASE" else th(b)
        hdr1.append(r"\multicolumn{" + str(len(idx)) + r"}{c}{vs.\ " + ref + "}")
    out.append(" & ".join(hdr1) + r" \\")
    c = 3
    rules = []
    for idx in groups.values():
        rules.append(r"\cmidrule(lr){" + f"{c}-{c + len(idx) - 1}" + "}")
        c += len(idx)
    out.append("".join(rules))
    out.append(" & ".join(["Workload", "Time"] + [th(cols[i][0]) for i in order]) + r" \\")
    out.append(r"\midrule")
    prev = None
    for wid, info, base, metric, cells in rows:
        if prev is not None and wid != prev:
            out.append(r"\addlinespace")
        name = ""
        if wid != prev:
            name = info.title.replace("×", r"$\times$") + f" (${info.symbol}$)"
            if base != "js":
                name += r"\textsuperscript{a}"
        prev = wid
        out.append(" & ".join([name, short[metric]] + [cells[i] for i in order]) + r" \\")
    out.append(r"\bottomrule")
    out.append(r"\end{tabular}")
    notes = sorted({(info.title, base) for _, info, base, _, _ in rows if base != "js"})
    if notes:
        txt = "; ".join(f"{t}: JS is \\texttt{{{b}}}" for t, b in notes)
        out.append(r"\par\smallskip\footnotesize\textsuperscript{a}" + txt + ".")
    out.append(r"\end{table*}")
    return "\n".join(out) + "\n"


def runs_table(ds_runs: pd.DataFrame, selection: pd.DataFrame) -> str:
    lines = ["| Browser | Workload | Run | Notes | Commit | Used |", "|---|---|---|---|---|---|"]
    runs = ds_runs.set_index("run_id")
    for r in selection.itertuples():
        run = runs.loc[r.run_id]
        lines.append(
            f"| {run.browser_label} | {r.workload} | `{Path(run.file).name}` | {run.notes or ''} | "
            f"`{str(run.commit)[:12]}` | {'✓' if r.used else ''} |"
        )
    return "\n".join(lines)


def warnings_for(ds_runs: pd.DataFrame, selection: pd.DataFrame, summary: pd.DataFrame) -> list[str]:
    out = []
    used = ds_runs[ds_runs["run_id"].isin(selection.loc[selection["used"], "run_id"])]
    for r in used.itertuples():
        if not r.complete:
            out.append(f"`{Path(r.file).name}` is incomplete (the run was stopped); only finished records are analysed.")
        if "battery" in str(r.notes).lower():
            out.append(f"`{Path(r.file).name}` was recorded on battery: CPU workers may have run on the efficiency cores.")
        if r.timestamp_resolution_ns and r.timestamp_resolution_ns > 1000:
            out.append(f"`{Path(r.file).name}`: GPU timestamps are quantized to {r.timestamp_resolution_ns:,} ns, "
                       "so short kernels' `kernel` times are coarse.")
        if r.browser == "firefox":
            out.append(f"`{Path(r.file).name}` is Firefox: its GPU compute and end-to-end phases wait for a 100 ms poll "
                       "(README, milestone 5), so only the `kernel` metric measures the GPU.")
    bad = summary[summary["status"].isin(["invalid", "error"])]
    for r in bad.itertuples():
        out.append(f"{r.browser} {r.workload} {r.implementation} at {r.size}: **{r.status}** {r.message}")
    noisy = summary[(summary["status"] == "ok") & (summary["compute_iqr_pct"] > 25)]
    if len(noisy):
        out.append(f"{len(noisy)} of {int((summary['status'] == 'ok').sum())} records have a compute-phase IQR above "
                   "25 % of the median (see `summary.csv`, `compute_iqr_pct`).")
    return out
